"""QA da parte do produtor nos insumos (50% dele, 50% da proprietária) e da escolha
"só esta / esta e as próximas" ao mudar o valor de uma parcela ou assinatura no cartão.
Uso: python parte_produtor_cartao.py [pasta-de-saida]   (servidor do build em http://localhost:8765/)"""
import asyncio, sys, os, tempfile
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from comum import preparar, pular_tour
from insumos import ir, ultimo_toast, limpar_toasts, adicionar, lancar
from recorrencia_cartao import mes, conteudo, novo_cartao
from playwright.async_api import async_playwright
U = 'http://localhost:8765/'
SAIDA = sys.argv[1] if len(sys.argv) > 1 else tempfile.mkdtemp()
CHROME = next((c for c in [r'C:\Program Files\Google\Chrome\Application\chrome.exe', '/usr/bin/google-chrome'] if os.path.exists(c)), None)
R = []
def ok(n, c, x=''): R.append(('PASS' if c else 'FALHA', n, x))

async def abrir_compra(pg, desc):
    await pg.locator('#conteudo li', has_text=desc).locator('[data-editar-compra]').first.click()
    await pg.wait_for_selector('dialog[open] form')

async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path=CHROME) if CHROME else await p.chromium.launch()
        ctx = await b.new_context(viewport={'width': 1280, 'height': 900})
        pg = await ctx.new_page()
        erros = []
        pg.on('pageerror', lambda e: erros.append(str(e)))
        await preparar(pg, U, exemplo=True); await pular_tour(pg)

        # ---------- insumos: parte do produtor
        await ir(pg, 'ajustes')
        await pg.click('[data-secao=modulos] summary'); await pg.check('[data-modulo-resina]'); await pg.wait_for_timeout(800)
        await ir(pg, 'resina-cadastros')
        await adicionar(pg, 'resina_titulares', {'nome': 'Empresa', 'documento': '12.345.678/0001-90'})
        await adicionar(pg, 'resina_produtores', {'nome': 'João', 'arrendamento': 40})
        await adicionar(pg, 'resina_produtos', {'nome': 'Pasta estimulante', 'unidade': 'kg', 'valor_unitario': '5000'})
        await ir(pg, 'insumos'); await pg.click('[data-lancar]'); await pg.wait_for_selector('dialog[open] [data-c=pct]')
        ok('campo parte do produtor vem com 50', await pg.input_value('dialog[open] [data-c=pct]') == '50')
        await pg.keyboard.press('Escape'); await pg.wait_for_timeout(300)
        total, t = await lancar(pg, 'João', '2026-11-04', [('Pasta estimulante', 20, None)])
        ok('entrega de R$ 1.000 lançada', total == 'R$ 1.000,00', (total, t))
        c = await conteudo(pg)
        ok('lista mostra a divisão', 'Produtor paga R$ 500,00' in c and 'proprietária R$ 500,00' in c, c[:600])
        await ir(pg, 'inicio'); await pg.wait_for_timeout(500)
        c = await conteudo(pg)
        ok('Início: falta receber só a parte do produtor (R$ 500)', 'R$ 500,00' in c and 'Falta receber' in c and 'R$ 1.000,00 Falta' not in c)
        await ir(pg, 'conta-corrente'); await pg.wait_for_timeout(500)
        c = await conteudo(pg)
        ok('conta corrente: débito de R$ 500', '500,00' in c and '1.000,00' in c and '50% de R$ 1.000,00' in c, c[:1200])
        # mudar para 100%: volta a cobrar tudo
        await ir(pg, 'insumos'); await pg.click('[data-entrega] >> text=João'); await pg.wait_for_selector('dialog[open] [data-c=pct]')
        ok('editar abre com 50', await pg.input_value('dialog[open] [data-c=pct]') == '50')
        await pg.fill('dialog[open] [data-c=pct]', '150'); await pg.click('dialog[open] button[type=submit]'); await pg.wait_for_timeout(300)
        ok('% acima de 100 bloqueado', 'de 0 a 100' in await pg.inner_text('dialog[open]'))
        await pg.fill('dialog[open] [data-c=pct]', '100')
        ok('divisão ao vivo', 'Cobrado de João (Empresa · 12.345.678/0001-90): R$ 1.000,00' in (await pg.inner_text('dialog[open] [data-divisao]')).replace('\xa0', ' '))
        await pg.click('dialog[open] button[type=submit]'); await pg.wait_for_timeout(800)
        await ir(pg, 'inicio'); await pg.wait_for_timeout(500)
        ok('Início: com 100% falta receber R$ 1.000', 'R$ 1.000,00' in await conteudo(pg))

        # ---------- "a receber" no Caixa: marcar como recebido baixa a conta corrente
        await ir(pg, 'insumos'); await pg.click('[data-entrega] >> text=João'); await pg.wait_for_selector('dialog[open] [data-c=pct]')
        ok('a receber vem marcado na entrega', await pg.locator('dialog[open] [name=cx_receber]').is_checked())
        await pg.fill('dialog[open] [data-c=pct]', '50'); await pg.click('dialog[open] button[type=submit]'); await pg.wait_for_timeout(800)
        await ir(pg, 'extrato'); await pg.wait_for_timeout(500)
        item = pg.locator('#conteudo li', has_text='A receber · insumos (Pasta estimulante 50%) · João')
        ok('Extrato: entrada a receber de R$ 500 (só uma)', await item.count() == 1 and 'R$ 500,00' in (await item.inner_text()).replace('\xa0', ' '))
        await item.locator('[data-pagar]').click(); await pg.wait_for_timeout(800)
        await ir(pg, 'inicio'); await pg.wait_for_timeout(500)
        c = await conteudo(pg)
        ok('Início: recebido no Caixa, nada falta receber', 'Falta receber' not in c, c[:900])
        await ir(pg, 'conta-corrente'); await pg.wait_for_timeout(500)
        c = await conteudo(pg)
        ok('conta corrente: crédito do Caixa aparece', 'Recebido no Caixa' in c and '500,00' in c, c[:1500])
        # mudar a entrega depois de recebida mantém recebido
        await ir(pg, 'insumos'); await pg.click('[data-entrega] >> text=João'); await pg.wait_for_selector('dialog[open] [data-c=pct]')
        ok('entrega mostra que já foi recebido', 'Já foi recebido' in await pg.inner_text('dialog[open]'))
        await pg.click('dialog[open] button[type=submit]'); await pg.wait_for_timeout(800)
        await ir(pg, 'inicio'); await pg.wait_for_timeout(500)
        ok('salvar de novo não reabre o falta receber', 'Falta receber' not in await conteudo(pg))

        # ---------- uma nota com dois produtores, cada produto com a sua %
        await ir(pg, 'resina-cadastros')
        await adicionar(pg, 'resina_produtores', {'nome': 'Carlos', 'arrendamento': 40})
        await adicionar(pg, 'resina_produtos', {'nome': 'Arame', 'unidade': 'm', 'valor_unitario': '1000'})
        total, t = await lancar(pg, 'João', '2026-11-10', [('Arame', 10, None, 'João', 50), ('Pasta estimulante', 4, None, 'Carlos', 30)])
        ok('nota com 2 produtores: total R$ 300', total == 'R$ 300,00' and 'João e Carlos' in t, (total, t))
        c = await conteudo(pg)
        ok('lista: parte de cada um', 'João paga R$ 50,00' in c and 'Carlos paga R$ 60,00' in c and 'proprietária R$ 190,00' in c, c[:1500])
        ok('lista: produtor e % em cada produto', '(João, 50% do produtor)' in c and '(Carlos, 30% do produtor)' in c, c[:1500])
        await ir(pg, 'extrato'); await pg.wait_for_timeout(500)
        a = pg.locator('#conteudo li', has_text='A receber · insumos (Arame 50%) · João')
        b2 = pg.locator('#conteudo li', has_text='A receber · insumos (Pasta estimulante 30%) · Carlos')
        ok('Extrato: um a receber para cada produtor', await a.count() == 1 and await b2.count() == 1
           and 'R$ 50,00' in (await a.inner_text()).replace('\xa0', ' ') and 'R$ 60,00' in (await b2.inner_text()).replace('\xa0', ' '))
        await ir(pg, 'conta-corrente'); await pg.wait_for_timeout(500)
        c = await conteudo(pg)
        ok('conta corrente: débito de cada produtor', '50% de R$ 100,00' in c and '30% de R$ 200,00' in c, c[:2500])
        # mudar a % do Carlos: a entrada dele acompanha, a do João continua
        await ir(pg, 'insumos'); await pg.click('[data-entrega] >> text=Carlos'); await pg.wait_for_selector('dialog[open] [data-c=pct]')
        await pg.locator('dialog[open] [data-c=pct]').nth(1).fill('40')
        ok('divisão ao vivo por produtor', 'Cobrado de Carlos (Empresa · 12.345.678/0001-90): R$ 80,00' in (await pg.inner_text('dialog[open] [data-divisao]')).replace('\xa0', ' '))
        await pg.screenshot(path=os.path.join(SAIDA, 'insumos-dois-produtores.png'), full_page=True)
        await pg.click('dialog[open] button[type=submit]'); await pg.wait_for_timeout(800)
        await ir(pg, 'extrato'); await pg.wait_for_timeout(500)
        b2 = pg.locator('#conteudo li', has_text='A receber · insumos (Pasta estimulante 40%) · Carlos')
        ok('mudar a %: a receber do Carlos vira R$ 80 e o do João continua', await b2.count() == 1 and 'R$ 80,00' in (await b2.inner_text()).replace('\xa0', ' ')
           and await pg.locator('#conteudo li', has_text='A receber · insumos (Arame 50%) · João').count() == 1
           and await pg.locator('#conteudo li', has_text='Pasta estimulante 30%').count() == 0)

        # ---------- "Quando vai receber?": acompanha o vencimento da nota até a pessoa mudar
        await ir(pg, 'insumos'); await pg.click('[data-entrega] >> text=Carlos'); await pg.wait_for_selector('dialog[open] [name=cx_data_receber]')
        rec = 'dialog[open] [name=cx_data_receber]'
        ok('quando vai receber: lançado antes vem com a data da compra', await pg.input_value(rec) == '2026-11-10', await pg.input_value(rec))
        await pg.check('dialog[open] [name=cx_modo][value=saida]'); await pg.wait_for_timeout(100)
        await pg.fill('dialog[open] [name=cx_vencimento]', '2026-11-25'); await pg.wait_for_timeout(100)
        ok('quando vai receber acompanha o vencimento da nota', await pg.input_value(rec) == '2026-11-25', await pg.input_value(rec))
        await pg.fill(rec, '2026-11-28')
        await pg.fill('dialog[open] [name=cx_vencimento]', '2026-11-26'); await pg.wait_for_timeout(100)
        ok('depois de mudar a mão, não acompanha mais', await pg.input_value(rec) == '2026-11-28', await pg.input_value(rec))
        await pg.fill(rec, ''); await pg.click('dialog[open] button[type=submit]'); await pg.wait_for_timeout(300)
        ok('sem data de receber: pede a data', 'Escolha quando vai receber' in await pg.inner_text('dialog[open]'))
        await pg.fill(rec, '2026-11-28'); await pg.click('dialog[open] button[type=submit]'); await pg.wait_for_timeout(800)
        await ir(pg, 'insumos'); await pg.click('[data-entrega] >> text=Carlos'); await pg.wait_for_selector(f'{rec}')
        ok('a receber gravado no dia escolhido', await pg.input_value(rec) == '2026-11-28', await pg.input_value(rec))
        await pg.keyboard.press('Escape'); await pg.wait_for_timeout(300)
        await pg.click('[data-lancar]'); await pg.wait_for_selector(f'{rec}')
        await pg.fill('#in-data', '2026-11-12'); await pg.wait_for_timeout(100)
        ok('entrega nova: quando vai receber vem com a data da compra', await pg.input_value(rec) == '2026-11-12', await pg.input_value(rec))
        await pg.keyboard.press('Escape'); await pg.wait_for_timeout(300)

        # ---------- cartão: parcela com valor diferente
        t = await novo_cartao(pg, 'compra', '30000', 'Furadeira', parcelas='3')
        ok('compra 3x de R$ 100', '3 parcelas' in t, t)
        await ir(pg, 'cartoes'); await mes(pg, 1)
        await abrir_compra(pg, 'Furadeira')
        ok('campo valor desta parcela', await pg.locator('#e-vparcela').count() == 1 and await pg.input_value('#e-vparcela') == '100,00')
        await pg.fill('#e-vparcela', '12000'); await pg.click('dialog[open] button[type=submit]'); await pg.wait_for_timeout(400)
        ok('pergunta só esta / próximas', await pg.locator('dialog[open] [data-r=um]').count() == 1 and await pg.locator('dialog[open] [data-r=todos]').count() == 1)
        await limpar_toasts(pg); await pg.click('dialog[open] [data-r=um]'); await pg.wait_for_timeout(800)
        c = await conteudo(pg)
        ok('só esta: parcela 1 agora R$ 120', 'R$ 120,00' in c, c[:800])
        await mes(pg, 2)
        await abrir_compra(pg, 'Furadeira')
        ok('só esta: parcela 2 continua R$ 100', await pg.input_value('#e-vparcela') == '100,00')
        ok('total vira a soma (R$ 320)', await pg.input_value('dialog[open] [name=valor]') == '320,00', await pg.input_value('dialog[open] [name=valor]'))
        await pg.fill('#e-vparcela', '9000'); await pg.click('dialog[open] button[type=submit]'); await pg.wait_for_timeout(400)
        await pg.click('dialog[open] [data-r=todos]'); await pg.wait_for_timeout(800)
        await mes(pg, 3)
        await abrir_compra(pg, 'Furadeira')
        ok('esta e as próximas: parcela 3 R$ 90', await pg.input_value('#e-vparcela') == '90,00')
        ok('total R$ 300 (120 + 90 + 90)', await pg.input_value('dialog[open] [name=valor]') == '300,00', await pg.input_value('dialog[open] [name=valor]'))
        # cancelar não salva
        await pg.fill('#e-vparcela', '5000'); await pg.click('dialog[open] button[type=submit]'); await pg.wait_for_timeout(400)
        await pg.click('dialog[open] [data-r=""]'); await pg.wait_for_timeout(400)
        await pg.keyboard.press('Escape'); await pg.wait_for_timeout(300)
        await abrir_compra(pg, 'Furadeira')
        ok('cancelar não muda nada', await pg.input_value('#e-vparcela') == '90,00')
        await pg.keyboard.press('Escape'); await pg.wait_for_timeout(300)

        # ---------- cartão: assinatura, só este mês
        t = await novo_cartao(pg, 'compra', '3990', 'Streaming', parcelas='sempre')
        await ir(pg, 'cartoes'); await mes(pg, 2)
        await abrir_compra(pg, 'Streaming')
        await pg.fill('dialog[open] [name=valor]', '5990'); await pg.click('dialog[open] button[type=submit]'); await pg.wait_for_timeout(400)
        await pg.click('dialog[open] [data-r=um]'); await pg.wait_for_timeout(800)
        ok('assinatura: este mês R$ 59,90', 'R$ 59,90' in await conteudo(pg))
        await mes(pg, 3)
        await abrir_compra(pg, 'Streaming')
        ok('assinatura: mês seguinte segue R$ 39,90', await pg.input_value('dialog[open] [name=valor]') == '39,90')
        await pg.fill('dialog[open] [name=valor]', '4590'); await pg.click('dialog[open] button[type=submit]'); await pg.wait_for_timeout(400)
        await pg.click('dialog[open] [data-r=todos]'); await pg.wait_for_timeout(800)
        await mes(pg, 6)
        await abrir_compra(pg, 'Streaming')
        ok('assinatura: este e os próximos R$ 45,90', await pg.input_value('dialog[open] [name=valor]') == '45,90')
        await pg.keyboard.press('Escape'); await pg.wait_for_timeout(300)

        # ---------- cartão: busca (lupa) pela descrição ou pelo valor
        await ir(pg, 'cartoes'); await mes(pg, 3)
        visiveis = lambda: pg.locator('#conteudo section.card li[data-busca]:visible').count()
        antes = await visiveis()
        await pg.fill('#c-busca', '90,00'); await pg.wait_for_timeout(600)
        nomes = await pg.locator('#conteudo section.card li[data-busca]:visible').all_inner_texts()
        ok('busca pelo valor acha a parcela de R$ 90', any('Furadeira' in n for n in nomes) and await visiveis() < antes, (antes, nomes))
        await pg.fill('#c-busca', 'furadeira'); await pg.wait_for_timeout(600)
        outras = (await pg.inner_text('[data-outras]')).replace('\xa0', ' ')
        ok('busca mostra as outras faturas', 'Nas outras faturas: 2 resultados' in outras, outras[:300])
        await pg.locator('[data-editar-outra]').first.click(); await pg.wait_for_selector('dialog[open] form')
        ok('resultado de outra fatura abre a compra', 'Furadeira' in await pg.input_value('dialog[open] [name=descricao]'))
        await pg.keyboard.press('Escape'); await pg.wait_for_timeout(300)
        await pg.fill('#c-busca', 'xyzxyz'); await pg.wait_for_timeout(600)
        ok('nada encontrado', await visiveis() == 0 and 'nada encontrado' in await pg.inner_text('[data-outras]'))
        await mes(pg, 2)
        ok('busca continua ao trocar de mês', await pg.input_value('#c-busca') == 'xyzxyz')
        await pg.fill('#c-busca', ''); await pg.wait_for_timeout(400)
        ok('limpar a busca mostra tudo de novo', await visiveis() > 0 and await pg.inner_text('[data-outras]') == '')
        await ctx.close()
        cel = await b.new_context(viewport={'width': 390, 'height': 844})
        pc = await cel.new_page()
        await preparar(pc, U, exemplo=True); await pular_tour(pc)
        await ir(pc, 'cartoes')
        larg = await pc.evaluate('document.documentElement.scrollWidth')
        ok('celular: busca sem rolagem para o lado', larg <= 390 and await pc.locator('#c-busca').is_visible(), larg)
        await pc.screenshot(path=os.path.join(SAIDA, 'cartoes-busca-celular.png'))
        ok('sem erros no console', not erros, erros)
        await b.close()
    for r in R: print(r[0], r[1], '' if r[0] == 'PASS' else r[2])
    print(f"{sum(r[0] == 'PASS' for r in R)} passaram, {sum(r[0] != 'PASS' for r in R)} falharam")

if __name__ == '__main__':
    asyncio.run(main())
