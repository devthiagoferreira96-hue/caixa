// testa a conferência do backup direto (sem navegador)
globalThis.indexedDB = undefined;
const { conferirTabelas } = await import('../src/lib/api.js');
const { dadosIniciais } = await import('../src/lib/exemplo.js');
let ok = 0, falhas = [];
const t = (n, a, b) => { const s = JSON.stringify(a) === JSON.stringify(b); s ? ok++ : falhas.push(`${n}: ${JSON.stringify(a)} != ${JSON.stringify(b)}`); };
const d0 = dadosIniciais({ comExemplo: true }); const bom = d0.tabelas || d0;
const r = conferirTabelas(structuredClone(bom));
t('backup bom: nada corrigido', r.corrigidos, 0);
t('backup bom: nada ignorado', r.ignorados, 0);
for (const k of Object.keys(bom)) t(`backup bom: ${k} mesma quantidade`, r.tabelas[k].length, bom[k].length);
const ruim = structuredClone(bom);
ruim.lancamentos[0].valor = 'abc';
ruim.lancamentos[1].vencimento = 'ontem';
delete ruim.lancamentos[2].id;
ruim.lancamentos[3].conta_id = 'nao-existe';
ruim.lancamentos[4].valor = '1.234,56';
ruim.lancamentos[5].tipo = 'qualquer';
ruim.lancamentos[6].valor = -50;
ruim.lancamentos.push(structuredClone(ruim.lancamentos[7]));
ruim.lancamentos.push(null, 'texto', 42);
ruim.contas[0].saldo_inicial = '1.000,50';
ruim.categorias[0].nome = null;
ruim.cartoes[0].dia_fechamento = 45;
ruim.parcelas[0].compra_id = 'sumiu';
const r2 = conferirTabelas(ruim);
t('valor em texto inválido: ignorado', r2.tabelas.lancamentos.some((l) => l.id === ruim.lancamentos[0].id), false);
t('data inválida: ignorado', r2.tabelas.lancamentos.some((l) => l.id === ruim.lancamentos[1].id), false);
t('sem id: ganha um id', r2.tabelas.lancamentos.some((l) => l.descricao === ruim.lancamentos[2].descricao && l.id), true);
t('conta inexistente: fica sem conta', r2.tabelas.lancamentos.find((l) => l.id === ruim.lancamentos[3].id).conta_id, null);
t('"1.234,56" vira número', r2.tabelas.lancamentos.find((l) => l.id === ruim.lancamentos[4].id).valor, 1234.56);
t('tipo inválido: ignorado', r2.tabelas.lancamentos.some((l) => l.id === ruim.lancamentos[5].id), false);
t('valor negativo vira positivo', r2.tabelas.lancamentos.find((l) => l.id === ruim.lancamentos[6].id).valor, 50);
t('id repetido: só um', r2.tabelas.lancamentos.filter((l) => l.id === ruim.lancamentos[7].id).length, 1);
t('linhas que não são objetos: ignoradas', r2.tabelas.lancamentos.every((l) => typeof l === 'object' && l), true);
t('saldo em texto vira número', r2.tabelas.contas[0].saldo_inicial, 1000.5);
t('categoria sem nome ganha nome', r2.tabelas.categorias[0].nome, 'Categoria sem nome');
t('dia 45 corrigido', r2.tabelas.cartoes[0].dia_fechamento, 1);
t('parcela de compra que não existe: ignorada', r2.tabelas.parcelas.length, bom.parcelas.length - 1);
t('conta corrigidos e ignorados', [r2.corrigidos > 0, r2.ignorados], [true, 8]);
console.log(`${ok} passaram, ${falhas.length} falharam`); falhas.forEach((f) => console.log(' FALHA', f));
process.exit(falhas.length ? 1 : 0);
